"""Synthetic benchmark comparing predictive and reactive rescue routing policies."""

import json
import numpy as np

from .osm_loader import load_network
from .risk_engine import (
    calculate_edge_risk,
    BASE_RIVER_ELEVATION_M,
    RAINFALL_COEFFICIENT,
    ELEVATION_COEFFICIENT,
    RIVER_DISTANCE_COEFFICIENT,
    RISK_THRESHOLD_BIAS,
    ON_SCENE_DWELL_MIN,
)
from .router import RescueRouter, VehicleType
import modules.rescue_routing.risk_engine as risk_mod
import modules.rescue_routing.router as router_mod

BENCHMARK_SCENARIOS = 1000  # number of scenarios for synthetic benchmark evaluation
BENCHMARK_SEED = 42  # fixed seed guaranteeing deterministic benchmark reproducibility
BOOTSTRAP_RESAMPLES = 1000  # bootstrap resamples for 95% confidence intervals
BENCHMARK_DISCLAIMER = (
    "simulated floods generated by a model related to the router's risk model; not validated against real events"
)
WATER_LEVEL_RISE_RATE = 0.0003  # m/(mm/h)/min, plausible hydrograph rise rate
WATER_LEVEL_BASE_OFFSET_M = 0.1  # baseline standing water before intense storm
WATER_LEVEL_NOISE_STD_M = 0.15  # unmodelled local pooling and micro-topography
STORM_ACCUMULATION_HORIZON_MIN = 240.0  # assumed 4-hour antecedent rainfall accumulation prior to mission return


def compute_bootstrap_ci(data: list[float], n_boot: int = BOOTSTRAP_RESAMPLES, seed: int = BENCHMARK_SEED) -> dict:
    """Compute mean and 95% bootstrap confidence interval."""
    if not data:
        return {"mean": 0.0, "ci_95": [0.0, 0.0]}
    arr = np.array(data, dtype=float)
    rng = np.random.default_rng(seed)
    means = [
        float(np.mean(rng.choice(arr, size=len(arr), replace=True)))
        for _ in range(n_boot)
    ]
    return {
        "mean": round(float(np.mean(arr)), 4),
        "ci_95": [
            round(float(np.percentile(means, 2.5)), 4),
            round(float(np.percentile(means, 97.5)), 4),
        ],
    }


def run_benchmark(router: RescueRouter | None = None, output_path: str = "benchmark_results.json") -> dict:
    """Run 1000-scenario Monte Carlo benchmark and sensitivity analysis across two ground-truth models."""
    if router is None:
        graph = load_network()
        router = RescueRouter(graph)
    else:
        graph = router.graph

    rng = np.random.default_rng(BENCHMARK_SEED)
    edges_list = [tuple(sorted((u, v))) for u, v in graph.edges()]

    raw_v1 = {
        "AMBULANCE": {
            "all": {"pred_str": [], "react_str": [], "pen": []},
            "15-30": {"pred_str": [], "react_str": [], "pen": []},
            "30-45": {"pred_str": [], "react_str": [], "pen": []},
            "45-60": {"pred_str": [], "react_str": [], "pen": []},
        },
        "TRUCK_4X4": {
            "all": {"pred_str": [], "react_str": [], "pen": []},
            "15-30": {"pred_str": [], "react_str": [], "pen": []},
            "30-45": {"pred_str": [], "react_str": [], "pen": []},
            "45-60": {"pred_str": [], "react_str": [], "pen": []},
        },
    }

    raw_v2 = {
        "AMBULANCE": {
            "all": {"pred_str": [], "react_str": [], "pen": []},
            "15-30": {"pred_str": [], "react_str": [], "pen": []},
            "30-45": {"pred_str": [], "react_str": [], "pen": []},
            "45-60": {"pred_str": [], "react_str": [], "pen": []},
        },
        "TRUCK_4X4": {
            "all": {"pred_str": [], "react_str": [], "pen": []},
            "15-30": {"pred_str": [], "react_str": [], "pen": []},
            "30-45": {"pred_str": [], "react_str": [], "pen": []},
            "45-60": {"pred_str": [], "react_str": [], "pen": []},
        },
    }

    origin = "HOSPITAL_BASE"
    destination = "ZONE_NORTH_RESIDENTIAL"

    for _ in range(BENCHMARK_SCENARIOS):
        rainfall = float(rng.uniform(15.0, 60.0))
        depth_map = {}
        for u, v in edges_list:
            if rng.random() < 0.05:
                depth_map[(u, v)] = float(rng.uniform(0.1, 1.0))

        pert_rain = rainfall * float(rng.uniform(0.7, 1.3))
        pert_elev = {
            (u, v): graph[u][v]["elevation_meters"] + float(rng.uniform(-1.0, 1.0))
            for u, v in edges_list
        }

        if rainfall < 30.0:
            band_key = "15-30"
        elif rainfall < 45.0:
            band_key = "30-45"
        else:
            band_key = "45-60"

        for v_type in [VehicleType.AMBULANCE, VehicleType.TRUCK_4X4]:
            res = router.find_route(
                origin,
                destination,
                v_type,
                rainfall_rate=rainfall,
                depth_map=depth_map,
            )
            if res.get("status") != "OK":
                continue

            pred_path = res["path_nodes"]
            react_path = res["counterfactual"]["reactive_path_nodes"]
            pred_eta = res["eta_minutes"]
            react_eta = res["counterfactual"]["reactive_eta_min"]

            # Variant 1: Perturbed logistic risk model ground truth
            def eval_path_v1(path_nodes: list[str]) -> float:
                times = [
                    router._travel_time_s(
                        v_type,
                        graph[u_n][v_n],
                        depth_map.get(tuple(sorted((u_n, v_n))), graph[u_n][v_n].get("current_water_depth_meters", 0.0)),
                    )
                    for u_n, v_n in zip(path_nodes[:-1], path_nodes[1:])
                ]
                total_t_min = sum(times) / 60.0
                el_s = 0.0
                for i in range(len(path_nodes) - 1):
                    u_node, v_node = path_nodes[i], path_nodes[i + 1]
                    pair = tuple(sorted((u_node, v_node)))
                    edge_data = graph[u_node][v_node]
                    d = depth_map.get(pair, edge_data.get("current_water_depth_meters", 0.0))
                    if not router._is_passable(v_type, d):
                        return 1.0
                    h_exp = 2.0 * total_t_min + ON_SCENE_DWELL_MIN - (el_s / 60.0)
                    kind = edge_data.get("kind", "road")
                    r_true = calculate_edge_risk(
                        pert_elev[pair],
                        edge_data["distance_to_river_meters"],
                        pert_rain,
                        horizon_min=h_exp,
                        kind=kind,
                    )
                    if rng.random() < r_true:
                        return 1.0
                    el_s += times[i]
                return 0.0

            # Variant 2: Misspecified linear water level rise ground truth
            def eval_path_v2(path_nodes: list[str]) -> float:
                times = [
                    router._travel_time_s(
                        v_type,
                        graph[u_n][v_n],
                        depth_map.get(tuple(sorted((u_n, v_n))), graph[u_n][v_n].get("current_water_depth_meters", 0.0)),
                    )
                    for u_n, v_n in zip(path_nodes[:-1], path_nodes[1:])
                ]
                total_t_min = sum(times) / 60.0
                el_s = 0.0
                for i in range(len(path_nodes) - 1):
                    u_node, v_node = path_nodes[i], path_nodes[i + 1]
                    pair = tuple(sorted((u_node, v_node)))
                    edge_data = graph[u_node][v_node]
                    d = depth_map.get(pair, edge_data.get("current_water_depth_meters", 0.0))
                    if not router._is_passable(v_type, d):
                        return 1.0
                    h_exp = 2.0 * total_t_min + ON_SCENE_DWELL_MIN - (el_s / 60.0)
                    t = STORM_ACCUMULATION_HORIZON_MIN + h_exp
                    h_water = WATER_LEVEL_BASE_OFFSET_M + WATER_LEVEL_RISE_RATE * rainfall * t
                    elev = edge_data["elevation_meters"]
                    eps = float(rng.normal(0, WATER_LEVEL_NOISE_STD_M))
                    if h_water > (elev - BASE_RIVER_ELEVATION_M) + eps:
                        return 1.0
                    el_s += times[i]
                return 0.0

            p_str_1 = eval_path_v1(pred_path)
            r_str_1 = eval_path_v1(react_path)
            p_str_2 = eval_path_v2(pred_path)
            r_str_2 = eval_path_v2(react_path)

            v_dict_1 = raw_v1[v_type.value]
            v_dict_1["all"]["pred_str"].append(p_str_1)
            v_dict_1["all"]["react_str"].append(r_str_1)
            v_dict_1[band_key]["pred_str"].append(p_str_1)
            v_dict_1[band_key]["react_str"].append(r_str_1)

            if p_str_1 == 0.0 and r_str_1 == 0.0:
                eta_pen_1 = max(0.0, round(pred_eta - react_eta, 2))
                v_dict_1["all"]["pen"].append(eta_pen_1)
                v_dict_1[band_key]["pen"].append(eta_pen_1)

            v_dict_2 = raw_v2[v_type.value]
            v_dict_2["all"]["pred_str"].append(p_str_2)
            v_dict_2["all"]["react_str"].append(r_str_2)
            v_dict_2[band_key]["pred_str"].append(p_str_2)
            v_dict_2[band_key]["react_str"].append(r_str_2)

            if p_str_2 == 0.0 and r_str_2 == 0.0:
                eta_pen_2 = max(0.0, round(pred_eta - react_eta, 2))
                v_dict_2["all"]["pen"].append(eta_pen_2)
                v_dict_2[band_key]["pen"].append(eta_pen_2)

    def aggregate_metrics(raw_data: dict) -> tuple[dict, bool]:
        res_m = {}
        for v_name, v_data in raw_data.items():
            all_d = v_data["all"]
            bands_d = {}
            for b_name in ["15-30", "30-45", "45-60"]:
                b_raw = v_data[b_name]
                bands_d[b_name] = {
                    "scenarios_evaluated": len(b_raw["pred_str"]),
                    "predictive_stranded_rate": compute_bootstrap_ci(b_raw["pred_str"]),
                    "reactive_stranded_rate": compute_bootstrap_ci(b_raw["react_str"]),
                    "mean_eta_penalty_minutes": compute_bootstrap_ci(b_raw["pen"]),
                }

            b45_pred_ci = bands_d["45-60"]["predictive_stranded_rate"]["ci_95"]
            b45_react_ci = bands_d["45-60"]["reactive_stranded_rate"]["ci_95"]
            reduces_stranding = bool(b45_pred_ci[1] < b45_react_ci[0])

            res_m[v_name] = {
                "scenarios_evaluated": len(all_d["pred_str"]),
                "predictive_stranded_rate": compute_bootstrap_ci(all_d["pred_str"]),
                "reactive_stranded_rate": compute_bootstrap_ci(all_d["react_str"]),
                "mean_eta_penalty_minutes": compute_bootstrap_ci(all_d["pen"]),
                "bands": bands_d,
                "predictive_reduces_stranding": reduces_stranding,
            }
        amb_reduces = bool(res_m.get("AMBULANCE", {}).get("predictive_reduces_stranding", False))
        return res_m, amb_reduces

    metrics_v1, ambulance_reduces = aggregate_metrics(raw_v1)
    metrics_v2, ambulance_reduces_v2 = aggregate_metrics(raw_v2)

    ground_truth_variants = [
        {
            "variant": "perturbed_same_model",
            "description": "Monte Carlo evaluation where ground truth follows the same logistic risk model perturbed with parameter noise.",
            "sample_size": BENCHMARK_SCENARIOS,
            "overall": {
                v: {
                    "predictive_stranded_rate": metrics_v1[v]["predictive_stranded_rate"],
                    "reactive_stranded_rate": metrics_v1[v]["reactive_stranded_rate"],
                    "mean_eta_penalty_minutes": metrics_v1[v]["mean_eta_penalty_minutes"],
                }
                for v in ["AMBULANCE", "TRUCK_4X4"]
            },
            "by_rainfall_band": {
                b: {
                    v: {
                        "predictive_stranded_rate": metrics_v1[v]["bands"][b]["predictive_stranded_rate"],
                        "reactive_stranded_rate": metrics_v1[v]["bands"][b]["reactive_stranded_rate"],
                        "mean_eta_penalty_minutes": metrics_v1[v]["bands"][b]["mean_eta_penalty_minutes"],
                    }
                    for v in ["AMBULANCE", "TRUCK_4X4"]
                }
                for b in ["15-30", "30-45", "45-60"]
            },
        },
        {
            "variant": "misspecified_water_level",
            "description": "Simplified linear water-level model (not a hydraulic simulation); shares the elevation ordering of the route network, so it is a second mechanism check, not independent validation.",
            "sample_size": BENCHMARK_SCENARIOS,
            "overall": {
                v: {
                    "predictive_stranded_rate": metrics_v2[v]["predictive_stranded_rate"],
                    "reactive_stranded_rate": metrics_v2[v]["reactive_stranded_rate"],
                    "mean_eta_penalty_minutes": metrics_v2[v]["mean_eta_penalty_minutes"],
                }
                for v in ["AMBULANCE", "TRUCK_4X4"]
            },
            "by_rainfall_band": {
                b: {
                    v: {
                        "predictive_stranded_rate": metrics_v2[v]["bands"][b]["predictive_stranded_rate"],
                        "reactive_stranded_rate": metrics_v2[v]["bands"][b]["reactive_stranded_rate"],
                        "mean_eta_penalty_minutes": metrics_v2[v]["bands"][b]["mean_eta_penalty_minutes"],
                    }
                    for v in ["AMBULANCE", "TRUCK_4X4"]
                }
                for b in ["15-30", "30-45", "45-60"]
            },
        },
    ]

    named_constants = [
        "RAINFALL_COEFFICIENT",
        "ELEVATION_COEFFICIENT",
        "RIVER_DISTANCE_COEFFICIENT",
        "BASE_RIVER_ELEVATION_M",
        "RISK_THRESHOLD_BIAS",
        "ON_SCENE_DWELL_MIN",
    ]

    queries = [
        ("ambulance_hospital_to_north", "HOSPITAL_BASE", "ZONE_NORTH_RESIDENTIAL", VehicleType.AMBULANCE, False),
        ("truck_hospital_to_island", "HOSPITAL_BASE", "ZONE_ISLAND_COMMUNITY", VehicleType.TRUCK_4X4, False),
        ("boat_multimodal_hospital_to_island", "HOSPITAL_BASE", "ZONE_ISLAND_COMMUNITY", VehicleType.RESCUE_BOAT, True),
    ]
    rain_points = list(range(0, 65, 5))

    base_paths = {}
    for q_id, orig, dest, vt, is_multi in queries:
        for r in rain_points:
            if is_multi:
                out = router.find_multimodal_route(orig, dest, vt, rainfall_rate=float(r))
            else:
                out = router.find_route(orig, dest, vt, rainfall_rate=float(r))
            base_paths[(q_id, r)] = out.get("path_nodes")

    total_unchanged_cases = 0
    total_tested_cases = 0
    sensitivity = {}

    for const_name in named_constants:
        orig_val = getattr(risk_mod, const_name)
        const_res = {}
        for factor, label in [(0.8, "-20%"), (1.2, "+20%")]:
            perturbed_val = orig_val * factor
            setattr(risk_mod, const_name, perturbed_val)
            if const_name in dir(router_mod):
                setattr(router_mod, const_name, perturbed_val)

            unchanged = 0
            for q_id, orig, dest, vt, is_multi in queries:
                for r in rain_points:
                    if is_multi:
                        cur = router.find_multimodal_route(orig, dest, vt, rainfall_rate=float(r))
                    else:
                        cur = router.find_route(orig, dest, vt, rainfall_rate=float(r))
                    if cur.get("path_nodes") == base_paths[(q_id, r)]:
                        unchanged += 1

            total_q = len(queries) * len(rain_points)
            pct = round((unchanged / total_q) * 100.0, 1)
            const_res[label] = {
                "unchanged_count": unchanged,
                "total_queries": total_q,
                "pct_unchanged": pct,
            }
            total_unchanged_cases += unchanged
            total_tested_cases += total_q

        setattr(risk_mod, const_name, orig_val)
        if const_name in dir(router_mod):
            setattr(router_mod, const_name, orig_val)

        sensitivity[const_name] = const_res

    overall_pct_unchanged = round((total_unchanged_cases / total_tested_cases) * 100.0, 1)

    most_sensitive_constant = None
    min_mean_pct = 101.0
    for c_name, c_res in sensitivity.items():
        avg_pct = (c_res["-20%"]["pct_unchanged"] + c_res["+20%"]["pct_unchanged"]) / 2.0
        if avg_pct < min_mean_pct:
            min_mean_pct = avg_pct
            most_sensitive_constant = c_name

    payload = {
        "disclaimer": BENCHMARK_DISCLAIMER,
        "scenarios_count": BENCHMARK_SCENARIOS,
        "seed": BENCHMARK_SEED,
        "predictive_reduces_stranding": ambulance_reduces,
        "predictive_reduces_stranding_misspecified": ambulance_reduces_v2,
        "ground_truth_variants": ground_truth_variants,
        "metrics": metrics_v1,
        "sensitivity": {
            "overall_pct_unchanged": overall_pct_unchanged,
            "most_sensitive_constant": most_sensitive_constant,
            "most_sensitive_pct_unchanged": round(min_mean_pct, 1),
            "constants": sensitivity,
        },
    }

    if output_path:
        with open(output_path, "w", encoding="utf-8") as f:
            json.dump(payload, f, indent=2)

    return payload


if __name__ == "__main__":
    res = run_benchmark()
    print("=" * 60)
